"""Result from performance step."""

from dataclasses import dataclass

from jiro.results.base import Result


@dataclass
class PerformanceResult(Result):
    """Result from performance step.

    Attributes:
        changed_files: List of files modified (implementation files only)
        test_specifier: Full pytest specifier (e.g., "tests/test_perf.py::test_cache_speed")
        test_output: Output from running the test (showing it passes)
        benchmark_data: Optional performance metrics collected during optimization
        subagent_type: Type of subagent used (e.g., "claude-opus-4.5")
        subagent_prompt: The rendered prompt sent to the subagent
        tokens_in: Input tokens used by subagent
        tokens_out: Output tokens generated by subagent
        subagent_time: Time spent in subagent execution in seconds
    """

    test_specifier: str
    test_output: str
    benchmark_data: str | None
    subagent_type: str
    subagent_prompt: str
    tokens_in: int
    tokens_out: int
    subagent_time: float
