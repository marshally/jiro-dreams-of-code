"""Result from TDD refactor step."""

from dataclasses import dataclass

from jiro.results.base import Result


@dataclass
class TddRefactorResult(Result):
    """Result from TDD refactor step.

    Attributes:
        changed_files: List of files modified (implementation files only)
        test_specifier: Full pytest specifier (e.g., "tests/test_auth.py::test_login")
        test_output: Output from running the test (showing it passes)
        refactoring_type: Type of refactoring applied (e.g., "rename", "extract_method")
        checksum: Checksum from refactoring MCP proving behavior preservation
        subagent_type: Type of subagent used (e.g., "claude-opus-4.5")
        subagent_prompt: The rendered prompt sent to the subagent
        tokens_in: Input tokens used by subagent
        tokens_out: Output tokens generated by subagent
        subagent_time: Time spent in subagent execution in seconds
    """

    test_specifier: str
    test_output: str
    refactoring_type: str
    checksum: str
    subagent_type: str
    subagent_prompt: str
    tokens_in: int
    tokens_out: int
    subagent_time: float
