"""Result from config step."""

from dataclasses import dataclass

from jiro.results.base import Result


@dataclass
class ConfigResult(Result):
    """Result from config step.

    Attributes:
        changed_files: List of config files modified
        config_files_changed: Count of config files changed
        config_types: List of config file types changed (e.g., "yaml", "json", "toml")
        subagent_type: Type of subagent used (e.g., "claude-opus-4.5")
        subagent_prompt: The rendered prompt sent to the subagent
        tokens_in: Input tokens used by subagent
        tokens_out: Output tokens generated by subagent
        subagent_time: Time spent in subagent execution in seconds
    """

    config_files_changed: int
    config_types: list[str]
    subagent_type: str
    subagent_prompt: str
    tokens_in: int
    tokens_out: int
    subagent_time: float
