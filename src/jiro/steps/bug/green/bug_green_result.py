"""Result from bug green step."""

from dataclasses import dataclass
from pathlib import Path

from jiro.results.base import Result


@dataclass
class BugGreenResult(Result):
    """Result from bug green step.

    Attributes:
        changed_files: List of files modified (implementation files only)
        test_specifier: Full pytest specifier (e.g., "tests/test_auth.py::test_login_validates_email")
        test_output: Output from running the test (showing it passes)
        implementation_files: List of implementation files modified to fix bug
        subagent_type: Type of subagent used (e.g., "claude-opus-4.5")
        subagent_prompt: The rendered prompt sent to the subagent
        tokens_in: Input tokens used by subagent
        tokens_out: Output tokens generated by subagent
        subagent_time: Time spent in subagent execution in seconds
    """

    test_specifier: str
    test_output: str
    implementation_files: list[Path]
    subagent_type: str
    subagent_prompt: str
    tokens_in: int
    tokens_out: int
    subagent_time: float
