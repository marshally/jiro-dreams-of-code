"""Result from bug red step."""

from dataclasses import dataclass
from pathlib import Path

from jiro.results.base import Result


@dataclass
class BugRedResult(Result):
    """Result from bug red step.

    Attributes:
        changed_files: List of files modified (test files only)
        test_file: Path to the test file created
        test_name: The test function name (e.g., "test_login_bug_email_not_validated")
        test_specifier: Full pytest specifier (e.g., "tests/test_auth.py::test_login_bug_email_not_validated")
        test_output: Output from running the test (showing it fails, proving the bug exists)
        subagent_type: Type of subagent used (e.g., "claude-opus-4.5")
        subagent_prompt: The rendered prompt sent to the subagent
        tokens_in: Input tokens used by subagent
        tokens_out: Output tokens generated by subagent
        subagent_time: Time spent in subagent execution in seconds
    """

    test_file: Path
    test_name: str
    test_specifier: str
    test_output: str
    subagent_type: str
    subagent_prompt: str
    tokens_in: int
    tokens_out: int
    subagent_time: float
