"""Result from test only step."""

from dataclasses import dataclass
from pathlib import Path

from jiro.results.base import Result


@dataclass
class TestOnlyResult(Result):
    """Result from test only step.

    Attributes:
        changed_files: List of files modified (test files only)
        test_specifier: Full pytest specifier (e.g., "tests/test_auth.py::test_new_validation")
        test_output: Output from running the tests (showing they pass)
        test_files: List of test files that were modified
        subagent_type: Type of subagent used (e.g., "claude-opus-4.5")
        subagent_prompt: The rendered prompt sent to the subagent
        tokens_in: Input tokens used by subagent
        tokens_out: Output tokens generated by subagent
        subagent_time: Time spent in subagent execution in seconds
    """

    test_specifier: str
    test_output: str
    test_files: list[Path]
    subagent_type: str
    subagent_prompt: str
    tokens_in: int
    tokens_out: int
    subagent_time: float
