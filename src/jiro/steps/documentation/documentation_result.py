"""Result from documentation step."""

from dataclasses import dataclass

from jiro.results.base import Result


@dataclass
class DocumentationResult(Result):
    """Result from documentation step.

    Attributes:
        changed_files: List of files modified (documentation-only changes)
        doc_files_changed: Count of .md files changed
        py_files_changed: Count of .py files with doc-only changes
        subagent_type: Type of subagent used (e.g., "claude-opus-4.5")
        subagent_prompt: The rendered prompt sent to the subagent
        tokens_in: Input tokens used by subagent
        tokens_out: Output tokens generated by subagent
        subagent_time: Time spent in subagent execution in seconds
    """

    doc_files_changed: int
    py_files_changed: int
    subagent_type: str
    subagent_prompt: str
    tokens_in: int
    tokens_out: int
    subagent_time: float
